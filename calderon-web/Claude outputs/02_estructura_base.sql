-- 02 · Estructura completa de la base (solo lectura: no modifica nada y no trae datos ni secretos)
-- Correr en Supabase › SQL Editor y exportar el resultado como CSV (botón de descarga arriba del resultado).
-- Devuelve una fila por objeto con el SQL para volver a crearlo: tipos, secuencias, tablas,
-- restricciones, índices, vistas, funciones y triggers. Sirve para rearmar la base de prueba local.

with esquemas as (
  select oid, nspname
  from pg_namespace
  where nspname !~ '^pg_'
    and nspname not in (
      'information_schema', 'auth', 'storage', 'vault', 'extensions', 'graphql', 'graphql_public',
      'realtime', '_realtime', 'supabase_functions', 'supabase_migrations', 'net', 'cron', 'pgsodium',
      'pgsodium_masks', 'pgbouncer', 'pgtle', 'tiger', 'topology', 'pgmq', '_analytics'
    )
),
de_extension as (
  select objid from pg_depend where deptype = 'e'
),
tablas as (
  select c.oid, e.nspname, c.relname
  from pg_class c
  join esquemas e on e.oid = c.relnamespace
  where c.relkind in ('r', 'p')
    and c.oid not in (select objid from de_extension)
)

-- 01 extensiones
select 1 as orden, 'extension' as tipo, n.nspname as esquema, x.extname as nombre,
  format('create extension if not exists %I with schema %I;', x.extname, n.nspname) as ddl
from pg_extension x
join pg_namespace n on n.oid = x.extnamespace
where x.extname <> 'plpgsql'

union all
-- 02 esquemas
select 2, 'esquema', nspname, nspname, format('create schema if not exists %I;', nspname)
from esquemas
where nspname <> 'public'

union all
-- 03 enums
select 3, 'enum', e.nspname, t.typname,
  format('create type %I.%I as enum (%s);', e.nspname, t.typname,
    (select string_agg(quote_literal(l.enumlabel), ', ' order by l.enumsortorder)
     from pg_enum l where l.enumtypid = t.oid))
from pg_type t
join esquemas e on e.oid = t.typnamespace
where t.typtype = 'e'
  and t.oid not in (select objid from de_extension)

union all
-- 04 tipos compuestos
select 4, 'tipo', e.nspname, t.typname,
  format('create type %I.%I as (%s);', e.nspname, t.typname,
    (select string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod)), ', ' order by a.attnum)
     from pg_attribute a where a.attrelid = t.typrelid and a.attnum > 0 and not a.attisdropped))
from pg_type t
join esquemas e on e.oid = t.typnamespace
join pg_class c on c.oid = t.typrelid and c.relkind = 'c'
where t.typtype = 'c'
  and t.oid not in (select objid from de_extension)

union all
-- 05 dominios
select 5, 'dominio', e.nspname, t.typname,
  format('create domain %I.%I as %s%s;', e.nspname, t.typname, format_type(t.typbasetype, t.typtypmod),
    coalesce((select ' ' || string_agg(format('constraint %I %s', k.conname, pg_get_constraintdef(k.oid)), ' ')
              from pg_constraint k where k.contypid = t.oid), ''))
from pg_type t
join esquemas e on e.oid = t.typnamespace
where t.typtype = 'd'
  and t.oid not in (select objid from de_extension)

union all
-- 06 secuencias (las de columnas identity se crean solas con la tabla)
select 6, 'secuencia', s.schemaname, s.sequencename,
  format('create sequence if not exists %I.%I as %s increment %s minvalue %s maxvalue %s start %s%s;',
    s.schemaname, s.sequencename, s.data_type, s.increment_by, s.min_value, s.max_value, s.start_value,
    case when s.cycle then ' cycle' else '' end)
from pg_sequences s
join esquemas e on e.nspname = s.schemaname
join pg_class c on c.relname = s.sequencename and c.relnamespace = e.oid
where not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype in ('i', 'e'))

union all
-- 07 funciones (sin las de extensiones)
select 7, case p.prokind when 'p' then 'procedimiento' else 'funcion' end, e.nspname,
  p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
  pg_get_functiondef(p.oid) || ';'
from pg_proc p
join esquemas e on e.oid = p.pronamespace
where p.prokind in ('f', 'p')
  and p.oid not in (select objid from de_extension)

union all
-- 08 tablas (columnas, valores por defecto, not null, identity y columnas calculadas)
select 8, 'tabla', t.nspname, t.relname,
  format('create table %I.%I (%s);', t.nspname, t.relname,
    coalesce((
      select string_agg(
        format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case
             when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity'
             when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
             when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
             else ''
           end
        || case when a.attnotnull then ' not null' else '' end,
        ', ' order by a.attnum)
      from pg_attribute a
      left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
      where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
    ), ''))
from tablas t

union all
-- 09 restricciones: primero claves primarias, únicas y checks; después claves foráneas
select case when k.contype = 'f' then 10 else 9 end,
  case k.contype when 'p' then 'clave primaria' when 'u' then 'unica' when 'c' then 'check'
                 when 'x' then 'exclusion' else 'clave foranea' end,
  t.nspname, t.relname || '.' || k.conname,
  format('alter table %I.%I add constraint %I %s;', t.nspname, t.relname, k.conname, pg_get_constraintdef(k.oid))
from pg_constraint k
join tablas t on t.oid = k.conrelid
where k.contype in ('p', 'u', 'c', 'x', 'f')

union all
-- 11 índices que no vienen de una restricción
select 11, 'indice', t.nspname, i.relname, pg_get_indexdef(i.oid) || ';'
from pg_index x
join tablas t on t.oid = x.indrelid
join pg_class i on i.oid = x.indexrelid
where not exists (select 1 from pg_constraint k where k.conindid = x.indexrelid)

union all
-- 12 vistas y vistas materializadas
select 12, case c.relkind when 'v' then 'vista' else 'vista materializada' end, e.nspname, c.relname,
  case c.relkind
    when 'v' then format('create or replace view %I.%I%s as %s', e.nspname, c.relname,
      case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
      pg_get_viewdef(c.oid, true))
    else format('create materialized view %I.%I as %s', e.nspname, c.relname, pg_get_viewdef(c.oid, true))
  end
from pg_class c
join esquemas e on e.oid = c.relnamespace
where c.relkind in ('v', 'm')
  and c.oid not in (select objid from de_extension)

union all
-- 13 triggers
select 13, 'trigger', t.nspname, t.relname || '.' || g.tgname, pg_get_triggerdef(g.oid, true) || ';'
from pg_trigger g
join tablas t on t.oid = g.tgrelid
where not g.tgisinternal

order by 1, 3, 4;
