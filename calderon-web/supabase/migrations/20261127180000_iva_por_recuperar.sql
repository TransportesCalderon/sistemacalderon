       OR to_regprocedure('fin.fn_estado_resultados(date, date)') IS NULL THEN
        RAISE EXCEPTION 'Faltan los gastos o la contabilidad de Finanzas: avisar antes de seguir';
    END IF;
END $v$;

INSERT INTO ref.parametro (codigo, valor, descripcion)
SELECT x.codigo, x.valor, x.descripcion
  FROM (VALUES
    ('fin.iva_recuperar_desde', 'null'::jsonb, 'Migración 388: desde qué fecha se junta el IVA de las facturas para recuperar (null = desde la primera factura). Formato "AAAA-MM-DD".'),
    ('fin.iva_compras_pct', '19'::jsonb, 'Migración 388: tasa del IVA en Chile, para avisar las facturas cuyo IVA no es ese % del neto.')
  ) x(codigo, valor, descripcion)
 WHERE NOT EXISTS (SELECT 1 FROM ref.parametro p WHERE p.codigo = x.codigo AND p.eliminado_en IS NULL);

-- Lo que se recupera
CREATE TABLE IF NOT EXISTS fin.iva_recuperacion (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero           text NOT NULL UNIQUE,
    forma            text NOT NULL,
    fecha            date NOT NULL,                 -- cuándo se pidió (o se usó en el F29)
    periodo_desde    date,                          -- meses de compras que cubre (opcional)
    periodo_hasta    date,
    monto_solicitado numeric(14, 0) NOT NULL,
    estado           text NOT NULL,
    fecha_recuperada date,
    monto_recuperado numeric(14, 0),
    numero_tramite   text,
    nota             text,
    motivo           text,
    creado_en        timestamptz NOT NULL DEFAULT now(),
    creado_por       bigint,
    actualizado_en   timestamptz,
    actualizado_por  bigint,
    CONSTRAINT ck_ivr_forma CHECK (forma IN ('devolucion_exportador', 'f29', 'ajuste', 'otra')),
    CONSTRAINT ck_ivr_estado CHECK (estado IN ('solicitada', 'recuperada', 'rechazada', 'anulada')),
    CONSTRAINT ck_ivr_montos CHECK (monto_solicitado > 0 AND (monto_recuperado IS NULL OR (monto_recuperado > 0 AND monto_recuperado <= monto_solicitado))),
    CONSTRAINT ck_ivr_recuperada CHECK ((estado = 'recuperada') = (fecha_recuperada IS NOT NULL AND monto_recuperado IS NOT NULL)),
    CONSTRAINT ck_ivr_periodo CHECK (periodo_desde IS NULL OR periodo_hasta IS NULL OR periodo_hasta >= periodo_desde),
    CONSTRAINT ck_ivr_textos CHECK (coalesce(length(numero_tramite), 0) <= 60 AND coalesce(length(nota), 0) <= 500 AND coalesce(length(motivo), 0) <= 500)
);
COMMENT ON TABLE fin.iva_recuperacion IS 'Migración 388: lo que se recupera del IVA juntado de las facturas chilenas (devolución de exportador, F29, ajuste u otra).';
CREATE INDEX IF NOT EXISTS ix_ivr_estado ON fin.iva_recuperacion (estado);
