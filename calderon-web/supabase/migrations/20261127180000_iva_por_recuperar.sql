-- =====================================================================================
-- Migración 388 · IVA por recuperar: lo que se va juntando de las facturas chilenas con IVA y lo que se recupera
-- =====================================================================================
-- Pedido (27/11/2026): un apartado para ir calculando cuánto IVA deberíamos recuperar. Se toma de las facturas chilenas con
-- IVA, se va guardando y se descuenta a medida que se recupera.
--
--   · Lo que se junta (crédito fiscal): el IVA de los gastos con tipo «factura» vigentes (fin.gasto, pasado a CLP con su
--     cambio, sin las ligadas a una compra de vehículo) + el IVA de las compras de vehículos (fin.compra_rodado).
--     Desde el parámetro fin.iva_recuperar_desde (vacío = desde la primera factura).
--   · Lo que se recupera: tabla nueva fin.iva_recuperacion. Formas: devolución de exportador (se pide y queda «en trámite»
--     hasta que llega la plata o la rechazan), usado contra el débito en el F29, ajuste (lo recuperado antes del sistema) u otra.
--   · Por recuperar = lo juntado − lo recuperado. Disponible para pedir = por recuperar − lo que está en trámite.
--     La base no deja pedir ni registrar más de lo disponible.
--   · También muestra, para comparar: el débito fiscal de las ventas (cuenta de uso IVA_DEBITO) y el saldo de la cuenta
--     IVA crédito de la contabilidad. No hace asientos: el F29 y la devolución se siguen contabilizando como hasta hoy.
--   · Avisos: facturas con un IVA que no es el 19 % del neto, facturas sin número, facturas en otra moneda.
-- No cambia web.version_base. Se puede correr más de una vez. Las reglas del SII (quién puede pedir la devolución, plazos,
-- reajuste por UTM del remanente) no están en la cuenta: confirmarlas con el estudio contable.
-- =====================================================================================
