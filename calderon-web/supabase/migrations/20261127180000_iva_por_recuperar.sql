-- Las facturas que cuentan (interna)
CREATE OR REPLACE FUNCTION fin.fn_iva_facturas()
 RETURNS TABLE (fecha date, proveedor text, neto numeric, iva numeric, fuente text, moneda text, numero text, iva_doc numeric, neto_doc numeric)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public', 'extensions'
AS $f$
    WITH par AS (
        SELECT CASE WHEN jsonb_typeof(p.valor) = 'string' THEN (p.valor #>> '{}')::date END AS desde
          FROM (SELECT (SELECT valor FROM ref.parametro WHERE codigo = 'fin.iva_recuperar_desde' AND eliminado_en IS NULL) AS valor) p)
    SELECT g.fecha, coalesce(nullif(btrim(g.proveedor_nombre), ''), (SELECT pr.razon_social FROM mae.proveedor pr WHERE pr.id = g.proveedor_id), 'Sin proveedor'),
           round(g.neto * coalesce(g.tc_clp, 1)), round(g.iva * coalesce(g.tc_clp, 1)), 'factura', g.moneda::text, g.numero_documento, g.iva, g.neto
      FROM fin.gasto g, par
     WHERE g.eliminado_en IS NULL AND g.estado = 'vigente' AND g.tipo_documento = 'factura' AND g.iva > 0
       AND g.compra_rodado_id IS NULL AND (par.desde IS NULL OR g.fecha >= par.desde)
    UNION ALL
    SELECT r.fecha, coalesce((SELECT pr.razon_social FROM mae.proveedor pr WHERE pr.id = r.proveedor_id), 'Compra de vehículo'),
           round(r.valor_neto), round(r.iva), 'vehiculo', r.moneda::text, NULL, r.iva, r.valor_neto
      FROM fin.compra_rodado r, par
     WHERE r.estado = 'vigente' AND r.iva > 0 AND (par.desde IS NULL OR r.fecha >= par.desde)
$f$;
REVOKE ALL ON FUNCTION fin.fn_iva_facturas() FROM PUBLIC;
DO $p$ DECLARE g text; BEGIN
    FOR g IN SELECT r.rolname FROM pg_roles r WHERE r.rolname LIKE 'tc\_%' OR r.rolname IN ('authenticated', 'anon') LOOP
        EXECUTE format('REVOKE ALL ON FUNCTION fin.fn_iva_facturas() FROM %I', g);
    END LOOP;
END $p$;

-- Lo juntado, lo recuperado y lo que está en trámite (interna: la usan la lectura y las validaciones)
CREATE OR REPLACE FUNCTION fin.fn_iva_saldos(p_excluir bigint DEFAULT NULL)
 RETURNS TABLE (juntado numeric, recuperado numeric, en_tramite numeric, por_recuperar numeric, disponible numeric)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public', 'extensions'
AS $f$
    WITH j AS (SELECT coalesce(sum(f.iva), 0) AS juntado FROM fin.fn_iva_facturas() f),
    r AS (
        SELECT coalesce(sum(x.monto_recuperado) FILTER (WHERE x.estado = 'recuperada'), 0) AS recuperado,
               coalesce(sum(x.monto_solicitado) FILTER (WHERE x.estado = 'solicitada'), 0) AS en_tramite
          FROM fin.iva_recuperacion x WHERE x.id IS DISTINCT FROM p_excluir)
    SELECT j.juntado, r.recuperado, r.en_tramite, j.juntado - r.recuperado, j.juntado - r.recuperado - r.en_tramite FROM j, r
$f$;
REVOKE ALL ON FUNCTION fin.fn_iva_saldos(bigint) FROM PUBLIC;
DO $p$ DECLARE g text; BEGIN
    FOR g IN SELECT r.rolname FROM pg_roles r WHERE r.rolname LIKE 'tc\_%' OR r.rolname IN ('authenticated', 'anon') LOOP
        EXECUTE format('REVOKE ALL ON FUNCTION fin.fn_iva_saldos(bigint) FROM %I', g);
    END LOOP;
END $p$;

-- La lectura: resumen, mes a mes, proveedores, recuperaciones y avisos
CREATE OR REPLACE FUNCTION fin.fn_iva_por_recuperar()
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public', 'extensions'
 SET jit TO 'off'
AS $f$
DECLARE
    v_desde date; v_hoy date := mae.fn_hoy(); v_pct numeric := ref.fn_parametro_num('fin.iva_compras_pct', 19);
    s record; v_meses jsonb; v_prov jsonb; v_rec jsonb; v_avisos jsonb := '[]'; v_cont numeric; v_deb numeric;
    v_cta_cred smallint; v_cta_deb smallint; n_pct integer; n_sin_num integer; n_mon integer; v_primera date;
BEGIN
    PERFORM fin.fn_exigir_lectura_finanzas();
    SELECT CASE WHEN jsonb_typeof(valor) = 'string' THEN (valor #>> '{}')::date END INTO v_desde
      FROM ref.parametro WHERE codigo = 'fin.iva_recuperar_desde' AND eliminado_en IS NULL;
    SELECT * INTO s FROM fin.fn_iva_saldos();
    BEGIN v_cta_cred := fin.fn_cuenta_uso('IVA_CREDITO'); EXCEPTION WHEN OTHERS THEN v_cta_cred := NULL; END;
    BEGIN v_cta_deb := fin.fn_cuenta_uso('IVA_DEBITO'); EXCEPTION WHEN OTHERS THEN v_cta_deb := NULL; END;

    SELECT min(fecha) INTO v_primera FROM fin.fn_iva_facturas();

    -- Mes a mes: lo juntado, el débito de las ventas (para comparar), lo recuperado y el saldo que queda
    WITH meses AS (
        SELECT generate_series(date_trunc('month', coalesce(least(v_primera, (SELECT min(fecha) FROM fin.iva_recuperacion WHERE estado <> 'anulada')), v_hoy)),
                               date_trunc('month', v_hoy), interval '1 month')::date AS mes),
    f AS (SELECT date_trunc('month', fecha)::date AS mes, count(*) FILTER (WHERE fuente = 'factura') AS n, sum(neto) AS neto,
                 sum(iva) FILTER (WHERE fuente = 'factura') AS iva_f, sum(iva) FILTER (WHERE fuente = 'vehiculo') AS iva_v
            FROM fin.fn_iva_facturas() GROUP BY 1),
    d AS (SELECT date_trunc('month', a.fecha)::date AS mes, sum(l.haber - l.debe) AS deb
            FROM fin.asiento_linea l JOIN fin.asiento a ON a.id = l.asiento_id
           WHERE v_cta_deb IS NOT NULL AND l.cuenta_id = v_cta_deb GROUP BY 1),
    r AS (SELECT date_trunc('month', x.fecha_recuperada)::date AS mes, sum(x.monto_recuperado) AS rec
            FROM fin.iva_recuperacion x WHERE x.estado = 'recuperada' GROUP BY 1),
    t AS (SELECT m.mes, coalesce(f.n, 0) AS n, coalesce(f.neto, 0) AS neto, coalesce(f.iva_f, 0) AS iva_f, coalesce(f.iva_v, 0) AS iva_v,
                 coalesce(d.deb, 0) AS deb, coalesce(r.rec, 0) AS rec
            FROM meses m LEFT JOIN f ON f.mes = m.mes LEFT JOIN d ON d.mes = m.mes LEFT JOIN r ON r.mes = m.mes),
    ta AS (SELECT t.*, sum(t.iva_f + t.iva_v - t.rec) OVER (ORDER BY t.mes) AS acum FROM t)
    SELECT coalesce(jsonb_agg(jsonb_build_object(
               'mes', t.mes, 'facturas', t.n, 'neto', t.neto, 'iva_facturas', t.iva_f, 'iva_vehiculos', t.iva_v,
               'juntado', t.iva_f + t.iva_v, 'debito_ventas', t.deb, 'recuperado', t.rec,
               'por_recuperar_al_cierre', t.acum) ORDER BY t.mes DESC), '[]')
      INTO v_meses FROM ta t;

    -- Los proveedores que más IVA dejaron
    SELECT coalesce(jsonb_agg(jsonb_build_object('proveedor', z.proveedor, 'facturas', z.n, 'iva', z.iva) ORDER BY z.iva DESC), '[]') INTO v_prov
      FROM (SELECT proveedor, count(*) AS n, sum(iva) AS iva FROM fin.fn_iva_facturas() GROUP BY proveedor ORDER BY sum(iva) DESC LIMIT 10) z;

    -- Las recuperaciones
    SELECT coalesce(jsonb_agg(jsonb_build_object(
               'id', x.id, 'numero', x.numero, 'forma', x.forma, 'fecha', x.fecha, 'periodo_desde', x.periodo_desde, 'periodo_hasta', x.periodo_hasta,
               'monto_solicitado', x.monto_solicitado, 'estado', x.estado, 'fecha_recuperada', x.fecha_recuperada,
               'monto_recuperado', x.monto_recuperado, 'numero_tramite', x.numero_tramite, 'nota', x.nota, 'motivo', x.motivo)
             ORDER BY x.fecha DESC, x.id DESC), '[]') INTO v_rec
      FROM fin.iva_recuperacion x;

    -- Avisos
    SELECT count(*) FILTER (WHERE fuente = 'factura' AND neto_doc > 0 AND abs(iva_doc - neto_doc * v_pct / 100) > greatest(2, neto_doc * v_pct / 100 * 0.01)),
           count(*) FILTER (WHERE fuente = 'factura' AND nullif(btrim(coalesce(numero, '')), '') IS NULL),
           count(*) FILTER (WHERE moneda <> 'CLP')
      INTO n_pct, n_sin_num, n_mon FROM fin.fn_iva_facturas();
    IF n_pct > 0 THEN v_avisos := v_avisos || to_jsonb(format('%s factura%s con un IVA que no es el %s %% del neto: revisar que estén bien cargadas.', n_pct, CASE WHEN n_pct = 1 THEN '' ELSE 's' END, v_pct)); END IF;
    IF n_sin_num > 0 THEN v_avisos := v_avisos || to_jsonb(format('%s factura%s sin número de documento: el SII pide el folio de cada factura.', n_sin_num, CASE WHEN n_sin_num = 1 THEN '' ELSE 's' END)); END IF;
    IF n_mon > 0 THEN v_avisos := v_avisos || to_jsonb(format('%s factura%s en otra moneda: su IVA se pasó a pesos con el cambio cargado en cada una.', n_mon, CASE WHEN n_mon = 1 THEN '' ELSE 's' END)); END IF;

    -- Para comparar con la contabilidad
    IF v_cta_cred IS NOT NULL THEN
        SELECT coalesce(sum(l.debe - l.haber), 0) INTO v_cont FROM fin.asiento_linea l JOIN fin.asiento a ON a.id = l.asiento_id
         WHERE l.cuenta_id = v_cta_cred AND a.fecha <= v_hoy;
    END IF;
    IF v_cta_deb IS NOT NULL THEN
        SELECT coalesce(sum(l.haber - l.debe), 0) INTO v_deb FROM fin.asiento_linea l JOIN fin.asiento a ON a.id = l.asiento_id
         WHERE l.cuenta_id = v_cta_deb AND (v_desde IS NULL OR a.fecha >= v_desde);
    END IF;

    RETURN jsonb_build_object(
        'desde', coalesce(v_desde, v_primera), 'moneda', 'CLP', 'iva_pct', v_pct,
        'resumen', jsonb_build_object('juntado', s.juntado, 'recuperado', s.recuperado, 'en_tramite', s.en_tramite,
                                      'por_recuperar', s.por_recuperar, 'disponible_para_pedir', greatest(s.disponible, 0),
                                      'facturas', (SELECT count(*) FROM fin.fn_iva_facturas() WHERE fuente = 'factura'),
                                      'vehiculos', (SELECT count(*) FROM fin.fn_iva_facturas() WHERE fuente = 'vehiculo')),
        'comparar', jsonb_build_object('cuenta_iva_credito', v_cont, 'debito_ventas', v_deb),
        'meses', v_meses, 'proveedores', v_prov, 'recuperaciones', v_rec, 'avisos', v_avisos,
        'puede_editar', EXISTS (SELECT 1 FROM seg.usuario_rol WHERE usuario_id = aud.fn_usuario_actual() AND rol_codigo IN ('finanzas', 'ti')));
END $f$;
COMMENT ON FUNCTION fin.fn_iva_por_recuperar() IS
    'Migración 388: IVA por recuperar: lo juntado de las facturas chilenas con IVA (y compras de vehículos), lo recuperado, lo en trámite, mes a mes, proveedores y avisos.';

-- Registrar una recuperación (pedida o ya recuperada)
CREATE OR REPLACE FUNCTION fin.fn_guardar_iva_recuperacion(p_datos jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public', 'extensions'
AS $f$
DECLARE
    v_usr bigint := fin.fn_exigir_finanzas(); s record; v_id bigint; v_num text;
    v_forma text := p_datos ->> 'forma';
    v_fecha date := nullif(p_datos ->> 'fecha', '')::date;
    v_monto numeric := round(nullif(p_datos ->> 'monto', '')::numeric);
    v_ya boolean := coalesce((p_datos ->> 'ya_recuperada')::boolean, false);
    v_desde date := nullif(p_datos ->> 'periodo_desde', '')::date;
    v_hasta date := nullif(p_datos ->> 'periodo_hasta', '')::date;
BEGIN
    IF v_forma IS NULL OR v_forma NOT IN ('devolucion_exportador', 'f29', 'ajuste', 'otra') THEN RAISE EXCEPTION 'Elegí cómo se recupera' USING ERRCODE = '22023'; END IF;
    IF v_fecha IS NULL THEN RAISE EXCEPTION 'Poné la fecha' USING ERRCODE = '22023'; END IF;
    IF v_fecha > mae.fn_hoy() THEN RAISE EXCEPTION 'La fecha no puede ser futura' USING ERRCODE = '22023'; END IF;
    IF v_monto IS NULL OR v_monto <= 0 THEN RAISE EXCEPTION 'Poné el monto en pesos chilenos' USING ERRCODE = '22023'; END IF;
    IF v_desde IS NOT NULL AND v_hasta IS NOT NULL AND v_hasta < v_desde THEN RAISE EXCEPTION 'El período está al revés' USING ERRCODE = '22023'; END IF;
    -- El F29 y los ajustes ya están hechos: entran como recuperados
    IF v_forma IN ('f29', 'ajuste') THEN v_ya := true; END IF;
    SELECT * INTO s FROM fin.fn_iva_saldos();
    IF v_monto > s.disponible THEN
        RAISE EXCEPTION 'No hay tanto IVA para recuperar: quedan % CLP disponibles (por recuperar % menos % en trámite).',
              translate(to_char(greatest(s.disponible, 0), 'FM999G999G999G990'), ',', '.'), translate(to_char(s.por_recuperar, 'FM999G999G999G990'), ',', '.'),
              translate(to_char(s.en_tramite, 'FM999G999G999G990'), ',', '.') USING ERRCODE = '22023';
    END IF;
    v_num := 'IVR-' || lpad((coalesce((SELECT max(substr(numero, 5)::int) FROM fin.iva_recuperacion WHERE numero ~ '^IVR-\d+$'), 0) + 1)::text, 6, '0');
    INSERT INTO fin.iva_recuperacion (numero, forma, fecha, periodo_desde, periodo_hasta, monto_solicitado, estado, fecha_recuperada, monto_recuperado,
                                      numero_tramite, nota, creado_por)
    VALUES (v_num, v_forma, v_fecha, date_trunc('month', v_desde)::date, date_trunc('month', v_hasta)::date, v_monto,
            CASE WHEN v_ya THEN 'recuperada' ELSE 'solicitada' END, CASE WHEN v_ya THEN v_fecha END, CASE WHEN v_ya THEN v_monto END,
            nullif(btrim(p_datos ->> 'numero_tramite'), ''), nullif(btrim(p_datos ->> 'nota'), ''), v_usr)
    RETURNING id INTO v_id;
    RETURN jsonb_build_object('id', v_id, 'numero', v_num);
END $f$;

-- Lo que contestó el SII: llegó la plata (todo o parte) o la rechazaron
CREATE OR REPLACE FUNCTION fin.fn_resolver_iva_recuperacion(p_id bigint, p_recuperada boolean, p_fecha date, p_monto numeric, p_nota text DEFAULT NULL)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public', 'extensions'
AS $f$
DECLARE v_usr bigint := fin.fn_exigir_finanzas(); x fin.iva_recuperacion%ROWTYPE;
BEGIN
    SELECT * INTO x FROM fin.iva_recuperacion WHERE id = p_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'No encuentro esa recuperación' USING ERRCODE = 'P0002'; END IF;
    IF x.estado <> 'solicitada' THEN RAISE EXCEPTION 'Solo se resuelve lo que está en trámite' USING ERRCODE = '22023'; END IF;
    IF p_fecha IS NULL OR p_fecha < x.fecha OR p_fecha > mae.fn_hoy() THEN RAISE EXCEPTION 'Poné la fecha (entre el pedido y hoy)' USING ERRCODE = '22023'; END IF;
    IF p_recuperada THEN
        IF p_monto IS NULL OR round(p_monto) <= 0 OR round(p_monto) > x.monto_solicitado THEN
            RAISE EXCEPTION 'El monto recuperado va de 1 a % CLP (lo pedido). Si devolvieron menos, lo que falta vuelve a quedar disponible.',
                  translate(to_char(x.monto_solicitado, 'FM999G999G999G990'), ',', '.') USING ERRCODE = '22023';
        END IF;
        UPDATE fin.iva_recuperacion SET estado = 'recuperada', fecha_recuperada = p_fecha, monto_recuperado = round(p_monto),
               nota = coalesce(nullif(btrim(p_nota), ''), nota), actualizado_en = now(), actualizado_por = v_usr WHERE id = p_id;
    ELSE
        IF nullif(btrim(coalesce(p_nota, '')), '') IS NULL THEN RAISE EXCEPTION 'Escribí por qué la rechazaron' USING ERRCODE = '22023'; END IF;
        UPDATE fin.iva_recuperacion SET estado = 'rechazada', motivo = btrim(p_nota), actualizado_en = now(), actualizado_por = v_usr WHERE id = p_id;
    END IF;
END $f$;

-- Anular una cargada por error
CREATE OR REPLACE FUNCTION fin.fn_anular_iva_recuperacion(p_id bigint, p_motivo text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public', 'extensions'
AS $f$
DECLARE v_usr bigint := fin.fn_exigir_finanzas();
BEGIN
    IF nullif(btrim(coalesce(p_motivo, '')), '') IS NULL THEN RAISE EXCEPTION 'Escribí el motivo' USING ERRCODE = '22023'; END IF;
    UPDATE fin.iva_recuperacion SET estado = 'anulada', motivo = btrim(p_motivo), actualizado_en = now(), actualizado_por = v_usr
     WHERE id = p_id AND estado <> 'anulada';
    IF NOT FOUND THEN RAISE EXCEPTION 'No encuentro esa recuperación o ya está anulada' USING ERRCODE = 'P0002'; END IF;
END $f$;

-- Permisos: la lectura como el estado de resultados; las escrituras como el registro de compras de vehículos
DO $p$
DECLARE g text; x record;
BEGIN
    FOR x IN SELECT * FROM (VALUES ('fin.fn_iva_por_recuperar()', 'fin.fn_estado_resultados(date, date)'),
                                   ('fin.fn_guardar_iva_recuperacion(jsonb)', 'fin.fn_registrar_compra_rodado(jsonb)'),
                                   ('fin.fn_resolver_iva_recuperacion(bigint, boolean, date, numeric, text)', 'fin.fn_registrar_compra_rodado(jsonb)'),
                                   ('fin.fn_anular_iva_recuperacion(bigint, text)', 'fin.fn_registrar_compra_rodado(jsonb)')) v(f, modelo) LOOP
        EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC', x.f);
        FOR g IN SELECT r.rolname FROM pg_roles r WHERE r.rolname LIKE 'tc\_%' OR r.rolname IN ('authenticated', 'anon') LOOP
            IF to_regprocedure(x.modelo) IS NOT NULL AND has_function_privilege(g, x.modelo, 'EXECUTE') THEN
                EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO %I', x.f, g);
            ELSE
                EXECUTE format('REVOKE ALL ON FUNCTION %s FROM %I', x.f, g);
            END IF;
        END LOOP;
    END LOOP;
END $p$;

-- Prueba: la cuenta cierra y no deja recuperar de más (datos ZZ que se deshacen)
DO $t$
DECLARE s record; s2 record;
